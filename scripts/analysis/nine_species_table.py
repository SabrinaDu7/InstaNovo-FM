"""Render the nine-species results page: every scored run side by side, per species, with its provenance.

Input: the `<run>.json` files `nine_species_score.py` wrote, one per (sequencer, decoding) pair, named by their stem
(for example `fork-greedy.json`, `fork-beam5.json`, `casanovo-beam5.json`, `casanovo-greedy.json`). Output: a markdown
page with one table per metric (peptide recall over all sampled spectra with its 95 % peptide-bootstrap interval,
amino-acid precision, coverage, precision-coverage area), species as rows, runs as columns, plus per-run strata tables
(peptide recall by charge, length, modification presence, precursor m/z, peak count, pooled over species). Every number
is read from the JSON files; the page names them.

    python scripts/analysis/nine_species_table.py --scores docs/nine_species/results/scores --out docs/nine_species/results.md
"""
# ruff: noqa: T201  (command-line script: the result is printed)

from __future__ import annotations

import argparse
import json
from pathlib import Path


def fmt(x: float | None, pct: bool = False) -> str:
    if x is None or x != x:
        return "-"
    return f"{100 * x:.1f}" if pct else f"{x:.3f}"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scores", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    runs = {p.stem: json.loads(p.read_text()) for p in sorted(args.scores.glob("*.json"))}
    if not runs:
        raise SystemExit(f"no *.json under {args.scores}")
    species = sorted({sp for r in runs.values() for sp in r["species"]})
    lines = ["# Results: nine-species benchmark\n", f"Generated by `scripts/analysis/nine_species_table.py` from {', '.join(f'`{p.name}`' for p in sorted(args.scores.glob('*.json')))} "
             f"(each written by `scripts/analysis/nine_species_score.py`; rule: {next(iter(runs.values()))['rule']}). Peptide recall counts every sampled spectrum; "
             "the interval is a 95 % bootstrap over peptides.\n"]
    for metric, label, pct in (("peptide_recall", "Peptide recall over all sampled spectra (%)", True), ("aa_precision", "Amino-acid precision (%)", True),
                               ("coverage", "Coverage: share of spectra with a prediction", False), ("average_precision", "Precision-coverage area", False)):
        lines += [f"## {label}\n", "| species | " + " | ".join(runs) + " |", "| :---- |" + " ---: |" * len(runs)]
        for sp in species + ["all"]:
            cells = []
            for r in runs.values():
                e = r["species"].get(sp) if sp != "all" else r.get("all")
                if e is None:
                    cells.append("-")
                    continue
                v = fmt(e.get(metric), pct)
                ci = e.get("ci95", {}).get(metric) if sp != "all" else None
                cells.append(f"{v} ({fmt(ci[0], pct)} to {fmt(ci[1], pct)})" if ci else v)
            lines.append(f"| {sp} | " + " | ".join(cells) + " |")
        lines.append("")
    for key, label in (("charge", "precursor charge"), ("length", "peptide length"), ("modified", "label carries a modification"), ("precursor_mz", "precursor m/z"), ("n_peaks", "peaks in the spectrum")):
        lines += [f"## Peptide recall by {label} (%), pooled over species\n", "| group | " + " | ".join(f"{n} (spectra)" for n in runs) + " |", "| :---- |" + " ---: |" * len(runs)]
        groups = sorted({g for r in runs.values() for sp in r["species"].values() for g in sp["by"][key]}, key=lambda s: (len(s), s))
        for g in groups:
            cells = []
            for r in runs.values():
                n = sum(sp["by"][key].get(g, {}).get("spectra", 0) for sp in r["species"].values())
                hits = sum(sp["by"][key].get(g, {}).get("spectra", 0) * sp["by"][key].get(g, {}).get("peptide_recall", 0) for sp in r["species"].values())
                cells.append(f"{100 * hits / n:.1f} ({n:,})" if n else "-")
            lines.append(f"| {g} | " + " | ".join(cells) + " |")
        lines.append("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out}: {len(runs)} runs, {len(species)} species")


if __name__ == "__main__":
    main()
