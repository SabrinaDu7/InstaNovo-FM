"""Render `docs/arch_study/smoke.md`: the 10,000-step smoke runs of the architecture study beside the baseline at the
same step, every validation metric the trainer logged, plus step time and peak GPU memory, from the exported
`docs/references/rerun/train_smoke10k-<arm>/metrics.json` (`scripts/train/export_metrics.py smoke10k-<arm>`) and the
baseline's `train_40M_mcfm_90k_b2048/metrics.json` (`eval_step_10001`, exported with `--also-step 10001`). A cell is
"-" until its file exists. Re-run after every export.

    python scripts/train/smoke_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
RERUN = REPO / "docs" / "references" / "rerun"
DOC = REPO / "docs" / "arch_study" / "smoke.md"
STEP = 10001
ARMS = ("seed102", "meta-precursor", "pa-mask2mask", "ionladder")


def load(name: str) -> dict | None:
    path = RERUN / name / "metrics.json"
    return json.loads(path.read_text()) if path.exists() else None


def block(metrics: dict | None) -> dict[str, float]:
    """The `eval/*` metrics of step 10,001: the final block of a smoke run, `eval_step_10001` of the baseline."""
    if metrics is None:
        return {}
    for key in (f"final_eval_step_{STEP}", f"eval_step_{STEP}"):
        if key in metrics:
            return metrics[key]
    return {}


def fmt(value: object) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.4g}" if abs(value) < 1e4 else f"{value:,.0f}"
    return str(value)


def main() -> None:
    columns = [("baseline (seed 101), step 10,001", load("train_40M_mcfm_90k_b2048"))] + [
        (f"smoke `{arm}`", load(f"train_smoke10k-{arm}")) for arm in ARMS
    ]
    blocks = [block(m) for _, m in columns]
    keys = sorted({k for b in blocks for k in b})
    head = "| Metric | " + " | ".join(label for label, _ in columns) + " |"
    sep = "| :---- | " + " | ".join(":----" for _ in columns) + " |"
    rows = [f"| `{k}` | " + " | ".join(fmt(b.get(k)) for b in blocks) + " |" for k in keys]
    run_rows = []
    for label, field in (
        ("job", "job"),
        ("seconds per step (median of the log)", "seconds_per_step"),
        ("peak GPU memory (MiB)", "gpu_mem_peak_mib"),
        ("seed", "seed"),
        ("global batch", "global_batch"),
    ):
        run_rows.append(
            f"| {label} | "
            + " | ".join(fmt((m or {}).get("_run", {}).get(field)) for _, m in columns)
            + " |"
        )
    filled = {label: len(b) for (label, _), b in zip(columns, blocks)}
    text = "\n".join(
        [
            "# Smoke runs: 10,000 steps of four arms beside the baseline at the same step",
            "",
            "Generated by `scripts/train/smoke_results.py` from `docs/references/rerun/`; the runs are defined in `README.md` (same",
            "learning-rate trajectory as the baseline's first 10,000 steps, same data, same validation: 250 batches of MCFM validation).",
            "Read `meta-precursor` and `pa-mask2mask` with the caveat of `README.md`: their task is easier by construction, so a",
            'better masked-m/z number here is not by itself a better model. A "-" means the file does not exist yet.',
            "",
            "## Validation metrics at step 10,001",
            "",
            head,
            sep,
            *rows,
            "",
            "## Run",
            "",
            "| | " + " | ".join(label for label, _ in columns) + " |",
            sep,
            *run_rows,
        ]
    )
    DOC.write_text(text + "\n")
    print(f"wrote {DOC.relative_to(REPO)}; metrics per column: {filled}")  # noqa: T201


if __name__ == "__main__":
    main()
