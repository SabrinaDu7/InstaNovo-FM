"""Render `docs/arch_study/equal_step/README.md`: every equal-step comparison side by side, one table per training step.

Input: the folders `scripts/reproduce/equal_step.py` writes under `docs/arch_study/equal_step/`, named `<arm>_step<N>`
and `baseline_step<N>`, each holding the suite's `duplicateretrievaltask.json` and `linearprobetask.json` summaries
and `run.json`. Output: one markdown table per step with the baseline first, then every arm evaluated at that step;
a side whose folder is missing shows `-`. The table carries each cell's source folder, so a number is one `cat` away.

    python scripts/reproduce/equal_step_table.py
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ROOT = REPO / "docs" / "arch_study" / "equal_step"
DOC = ROOT / "README.md"

METRICS: tuple[tuple[str, str, str], ...] = (  # (file stem, key, label)
    ("duplicateretrievaltask", "recall@1", "retrieval recall@1"),
    ("duplicateretrievaltask", "map@20", "retrieval mAP@20"),
    ("duplicateretrievaltask", "prop_recall@1", "retrieval proportional recall@1"),
    ("duplicateretrievaltask", "cond_hcd_orbitrap_recall@1", "retrieval recall@1, HCD Orbitrap"),
    ("duplicateretrievaltask", "cond_cid_recall@1", "retrieval recall@1, CID"),
    ("linearprobetask", "precursor_mass/r2", "probe precursor mass R²"),
    ("linearprobetask", "precursor_mz/r2", "probe precursor m/z R²"),
    ("linearprobetask", "precursor_charge/macro_f1", "probe precursor charge macro-F1"),
    ("linearprobetask", "frag_type/macro_f1", "probe fragmentation type macro-F1"),
    ("linearprobetask", "search_instrument/macro_f1", "probe instrument macro-F1"),
    ("linearprobetask", "ptm_present/balanced_accuracy", "probe PTM present balanced accuracy"),
    ("linearprobetask", "modification_class/macro_f1", "probe modification class macro-F1"),
    ("linearprobetask", "hydrophobicity/r2", "probe hydrophobicity R²"),
    ("linearprobetask", "collision_energy/r2", "probe collision energy R²"),
    ("linearprobetask", "spectrum_confidence/r2", "probe spectrum confidence R²"),
)


def sides_by_step() -> dict[int, list[Path]]:
    """Folders grouped by training step, the baseline first, then the arms in name order."""
    groups: dict[int, list[Path]] = defaultdict(list)
    for folder in sorted(ROOT.glob("*_step*")):
        if (m := re.fullmatch(r"(.+)_step(\d+)", folder.name)) and folder.is_dir():
            groups[int(m.group(2))].append(folder)
    return {step: sorted(folders, key=lambda f: (not f.name.startswith("baseline_"), f.name)) for step, folders in sorted(groups.items())}


def value(folder: Path, stem: str, key: str) -> str:
    summary = folder / f"{stem}.json"
    if not summary.exists():
        return "-"
    v = json.loads(summary.read_text()).get(key)
    return "-" if v is None else f"{v:.3f}"


def table(step: int, folders: list[Path]) -> str:
    names = [f.name.removesuffix(f"_step{step}") for f in folders]
    runs = [json.loads((f / "run.json").read_text()) if (f / "run.json").exists() else {} for f in folders]
    protocol = {r.get("protocol") for r in runs} - {None}
    dataset = {r.get("dataset") for r in runs} - {None}
    head = f"## Step {step:,}\n\nProtocol {', '.join(sorted(protocol)) or '-'} on {', '.join(sorted(dataset)) or '-'}; sides: " + ", ".join(
        f"`{f.relative_to(REPO)}`" for f in folders
    )
    rows = ["| Metric | " + " | ".join(names) + " |", "| :---- |" + " ---: |" * len(names)]
    rows += [f"| {label} | " + " | ".join(value(f, stem, key) for f in folders) + " |" for stem, key, label in METRICS]
    return head + "\n\n" + "\n".join(rows)


def main() -> None:
    groups = sides_by_step()
    text = (
        "# Equal-step comparisons\n\nGenerated by `scripts/reproduce/equal_step_table.py` from the folders of "
        "`scripts/reproduce/equal_step.py`; an arm and the baseline at the same training step through one of the suite's paper "
        "protocols, so an arm can be read before it finishes. `-` marks a side not evaluated yet.\n\n" + "\n\n".join(table(s, f) for s, f in groups.items())
    )
    DOC.write_text(text + "\n")
    print(f"wrote {DOC.relative_to(REPO)}: " + "; ".join(f"step {s:,}: {', '.join(x.name for x in f)}" for s, f in groups.items()))


if __name__ == "__main__":
    main()
